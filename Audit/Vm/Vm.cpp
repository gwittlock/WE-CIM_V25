static jboolean GetApplicationHome( char *buf, jint bufsize )
{
    char *cp;
    GetModuleFileName(0, buf, bufsize);
    *strrchr(buf, '\\') = '\0'; /* remove .exe file name */
    if ((cp = strrchr(buf, '\\')) == 0)
	{
		/* This happens if the application is in a drive root, and
		 * there is no bin directory. */
		buf[0] = '\0';
		return JNI_FALSE;
    }

    *cp = '\0';  /* remove the bin\ part */
    return JNI_TRUE;
}

static jobjectArray NewPlatformStringArray( JNIEnv* env )
{
	jclass cls = env->FindClass( "java/lang/String" );
	jobjectArray ary = env->NewObjectArray( 1, cls, 0 );

	env->SetObjectArrayElement( ary, 0, NULL );

	return ary;
}

void Message( const char* format, ... )
{
	char msg[1024];

	va_list params;
	va_start( params, format );

	vsprintf_s( msg, 1024, format, params );

	MessageBox( NULL, msg, "JVMInit", MB_OK ); 
}

CString JVMDLLPathGet( const CString& jvmDllFolder )
{
	CString jvmDllPath;

	if ( !jvmDllFolder.IsEmpty() )
	{
	    struct stat s;

		jvmDllPath.Format( "%s%s", jvmDllFolder,"\\bin\\client\\jvm.dll" );

		if (stat(jvmDllPath, &s) != 0)
			jvmDllPath = "";  // not found
	}

	return jvmDllPath;
}

void JVMArgsInit( JavaVMInitArgs* args )
{
	char home[MAXPATHLEN];
	GetApplicationHome( home, sizeof(home) );

	sprintf_s( g_app_path, MAXPATHLEN, "-Dapplication.home=%s", home );
	sprintf_s( g_class_path, MAXPATHLEN, "-Djava.class.path=%s", g_classPath );
	
	//------

	memset( &g_options, 0, sizeof(g_options) );

	g_options[0].optionString = g_app_path;
	g_options[1].optionString = g_class_path;

	g_options[2].optionString = "vfprintf";
	g_options[2].extraInfo = &JVM_Vfprintf;

	g_options[3].optionString = "abort";
	g_options[3].extraInfo = &JVM_Abort;

	g_options[4].optionString = "exit";
	g_options[4].extraInfo = &JVM_Exit;

	//------

	memset( args, 0, sizeof(*args) );

	args->version  = JNI_VERSION_1_6;
	args->nOptions = NUMOPTIONS;
	args->options  = g_options;
	args->ignoreUnrecognized = false;
}

CReturn WengVmEnvStart()
{
	CReturn status;

	jclass cls;
	jmethodID mid;

	//=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=
	// Find our virtual machine environment class (WengVmEnv).
	cls = g_env->FindClass( JVMENVNAME );
        
	if (g_env->ExceptionOccurred() || cls == 0)
	{
		CString errMsg;
		errMsg.Format( "VM failed to find class <%s>", JVMENVNAME );
		status.User( IDS_JVM_EXCEPTION, errMsg );
		MessageBox( NULL, status.LastErrorMsg(), "foo", MB_OK );
		return status;
	}

	//=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=
	// Find the main() method.
	mid = g_env->GetStaticMethodID( cls, "main", "([Ljava/lang/String;)V" );
        
	if (g_env->ExceptionOccurred() || mid == 0)
	{
		status.Fatal( IDS_JVM_EXCEPTION, "VM failed to find method <main>" );
		MessageBox( NULL, status.LastErrorMsg(), "foo", MB_OK );
		return status;
	}

	if (DEBUGMSGS) MsgInit();  // support for Msg.Display() in WengVmEnv.java

	//=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=
	// Execute the main() method.
	jobjectArray foo = NewPlatformStringArray( g_env );
	g_env->CallStaticVoidMethod( cls, mid, foo );
        
	if ( g_env->ExceptionOccurred() )
	{
		status.Fatal( IDS_JVM_EXCEPTION, "VM failed to execute <main>" );
		MessageBox( NULL, status.LastErrorMsg(), "foo", MB_OK );
		return status;
	}
	
	if (DEBUGMSGS) MsgTerm();  // support for Msg.Display() in WengVmEnv.java

	return status;
}

CReturn StoragePathSet( const CString& storagePath )
{
	CReturn status;

	// Find our virtual machine environment class.
    jclass cls = g_env->FindClass( JVMENVNAME );

	// Find the StoragePathSet() method.
	jmethodID mid = g_env->GetStaticMethodID( cls, "StoragePathSet", "(Ljava/lang/String;)V" );
        
	if (g_env->ExceptionOccurred() || (mid == 0))
	{
		status.Fatal( IDS_JVM_EXCEPTION, "VM failed to find method <StoragePathSet>" );
	}
	else
	{
		// Execute the StoragePathSet() method.
		jstring jPath = g_env->NewStringUTF( storagePath );
		g_env->CallStaticVoidMethod( cls, mid, jPath );
        
		if ( g_env->ExceptionOccurred() )
			status.Fatal( IDS_JVM_EXCEPTION, "VM failed to execute <StoragePathSet>" );
	}

	return status;
}
