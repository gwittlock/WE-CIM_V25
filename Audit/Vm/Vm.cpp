// The classpath and storagePath parameters are critical to proper
// java VM execution.
//
// classPath is passed to the java compiler as in normal execution
//     eg. 'javac -classpath <classPath> Foo.java'
//
// storagePath is also passed to the java compiler as the '-d' option,
// the destination directory for the class-file that is generated by
// the compiler.  Though less apparent, storagePath is also used by
// the java VM via the java class SimpleLoader.  The entry point to
// its use is CVm::Execute().
//
// Failures can occur for many reasons:
//
// 1. Be sure to use the correct version of javac when compiling
//    the java-source for Weng.jar. Failure to do this results in
//    the message "VM failed to find class <WengVmEnv>". Likewise,
//    the compiler version must match the JVM version.
//
//    Your system environment, system variable PATH *must* specify
//    the appropriate paths; these were broken during experimentation
//    with jdk1.6 -- a painful lesson :-(
//
//    For posterity, the PATH necessary path components at this time are:
//       C:\jdk1.3.1\bin;C:\jdk1.3.1\jre\bin;
//
//    When things were broken, the path components were:
//       C:\Program Files\Java\jdk1.6.0_22\bin;C:\Program Files\Java\jdk1.6.0_22\jre\bin\client;
//
//    I'm not sure if the CurrentVersion setting (in the registry under
//    HKEY_LOCAL_MACHINE\Software\JavaSoft for jdk & jre) matter.
//
// 2. If you get an error stating some class can not be found:
//
//  .1 Validate your classpath.
//  .2 Make sure the missing class is either in classpath or in
//     a jar (or zip) that is in the classpath.
//  .3 Make sure all classes referenced by the supposed missing
//     class are also in the classpath (per .2 above)
//  .4 Make sure system-loaded libaries (ie. dlls loaded via calls
//     to System.loadLibrary) are present.
//
// 3. If you get an error message "FATAL ERROR <some garbage>"
//    verify the JNI method used matches the method signature.
//      eg. this problem was discovered with the following case
//            g_env->GetStaticMethodIDC(...,(L...;)V)
//            g_env->CallStaticIntMethod(...)
//
// 4. For the error message "Failed to execute method <execute>"
//    This is probably caused by an exception being thrown as a
//    result of referencing null in a java file.
//
// 5. For "VM failed to execute <main>"
//    This is likely caused by using the wrong version of javac.

CReturn CVm::Init( const CString& jvmDllFolder, const CString& classPath, const CString& storagePath )
{
	// eg. "c:\Ci\AdvMach\Debug\dlls\Ci.zip;c:\jdk1.3.1\lib\tools.jar;c:\jdk1.3.1\jre\lib\rt.jar"
	g_classPath = classPath;
	g_storagePath = storagePath;

	CReturn status = JVMInit( jvmDllFolder );
	return status;
}

void CVm::Term()
{
	JVMTerm();
}

bool CVm::IsOk()
{
	return (g_jvm != NULL);
}

CReturn CVm::Compile( const CString& javaClassPath )
{
	CString errMsg;
	CReturn status;

	if (DEBUGMSGS) MsgInit();  // support for Msg.Display() in WengVmEnv.java

	//=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=
	// Find our virtual machine environment class.
    jclass cls = g_env->FindClass( JVMENVNAME );
    
	if (g_env->ExceptionOccurred() || cls == 0)
	{
		errMsg.Format( "VM failed to find class <%s>", JVMENVNAME );
		status.Fatal( IDS_JVM_EXCEPTION, errMsg );
		return status;
	}

	//=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=
	// Find the compile() method.
    jmethodID mid = g_env->GetStaticMethodID(
		cls, "compile", "(Ljava/lang/String;Ljava/lang/String;)I" );

	if (g_env->ExceptionOccurred() || mid == 0)
	{
		status.Fatal( IDS_JVM_EXCEPTION, "Failed to find method <compile>" );
		return status;
	}

	//=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=
	// The class path should include the
	// path to the top level java file.
	CString completeClassPath;
	CPath tmpPath( javaClassPath );
	completeClassPath.Format( "%s;%s", tmpPath.DriveDir(), g_classPath );

	//=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=
	// Execute the compile() method.
	jstring classPath = g_env->NewStringUTF( completeClassPath );
	jstring javaFile = g_env->NewStringUTF( javaClassPath );

	ErrSysInit();

	// NOTE: A non-zero result is not necessarily fatal!
	int result = g_env->CallStaticIntMethod( cls, mid, classPath, javaFile );

	ErrSysTerm();

	if (DEBUGMSGS) MsgTerm();  // support for Msg.Display() in WengVmEnv.java

	if ( g_env->ExceptionOccurred() )
	{
		g_env->ExceptionDescribe();
		status.Fatal( IDS_JVM_EXCEPTION, "Failed to execute method <compile>" );
	}
	else if (ErrSysCount() > 0)
	{
		status = STATUS_ERROR;  // compilation errors
	}

	return status;
}

CReturn CVm::Execute( const CString& javaClassPath, bool localStoragePath )
{
	CString errMsg;
	CReturn status;

	CPath path( javaClassPath );

	// Find our virtual machine environment class.
    jclass cls = g_env->FindClass( JVMENVNAME );

	if (g_env->ExceptionOccurred() || cls == 0)
	{
		errMsg.Format( "VM failed to find class <%s>", JVMENVNAME );
		status.Fatal( IDS_JVM_EXCEPTION, errMsg );
		return status;
	}

	status = StoragePathSet( (localStoragePath ? path.DriveDir() : g_storagePath) );
	if ( !status.IsOk() )
		return status;

	// Following java standards, the class name
	// must match the source file name.
	CString className = path.FileName();
	jstring machineName = g_env->NewStringUTF( className );


	// Find the execute() method.
	jmethodID mid = g_env->GetStaticMethodID( cls, "execute", "(Ljava/lang/String;)I" );
    
	if (g_env->ExceptionOccurred() || mid == 0)
	{
		g_env->ExceptionDescribe();
		status.Fatal( IDS_JVM_EXCEPTION, "Failed to find method <execute>" );
		return status;
	}


	// Execute the execute() method.
	int result = g_env->CallStaticIntMethod( cls, mid, machineName );

	if (g_env->ExceptionOccurred() || result != 0)
	{
		g_env->ExceptionDescribe();
		status.Fatal( IDS_JVM_EXCEPTION, "Failed to execute method <execute>" );
		return status;
	}

	return status;
}

CReturn CVm::JVMInit( const CString& jvmDllFolder )
{
	CReturn status;

	// bool debug = (CRegister::Debug( "jvminit" ) != 0);
	bool debug = false;

	CString jvmDllPath = JVMDLLPathGet( jvmDllFolder );

	if ( jvmDllPath.IsEmpty() )
	{
		MessageBox( NULL, "FATAL ERROR: Unable to find jvm.dll", "Error", MB_OK );
		status.Fatal( IDS_JVM_EXCEPTION, "Unable to find jvm.dll" );
	}
	else
	{
		if ( debug ) Message( "Calling LoadLibrary(\"%s\")", jvmDllPath );

		HINSTANCE hinst = LoadLibrary( jvmDllPath );
		if ( debug ) Message( "hinst: 0x%08x", hinst );

		if (hinst == 0)
		{
			MessageBox( NULL, "FATAL ERROR: LoadLibrary() failed.", "Error", MB_OK );
			status.Fatal( IDS_JVM_EXCEPTION, "LoadLibrary() failed." );
		}
		else
		{
			JavaVMInitArgs args;
			JVMArgsInit( &args );

			if ( debug ) Message( "Calling JNI_CreateJavaVM()" );

			jint result = JNI_CreateJavaVM( &g_jvm, (void**) &g_env, &args );
			if ( debug ) Message( "result:%d", result );

			if (result == 0)
			{
				status = WengVmEnvStart();
				if ( status.IsOk() )
					status = StoragePathSet( g_storagePath );
			}
			else
			{
				status.Fatal( IDS_JVM_EXCEPTION, "VM failed to initialize" );
				MessageBox( NULL, status.LastErrorMsg(), "foo", MB_OK );
			}
		}
	}

	return status;
}

void CVm::JVMTerm()
{
	if (g_jvm != NULL)
	{
		g_jvm->DestroyJavaVM();
		g_jvm = NULL;
	}

	if (m_hLibModule != NULL)
	{
		FreeLibrary( m_hLibModule );
	}

	MsgTerm();
}


